import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import ts from 'typescript';
const source = await readFile(new URL('../src/soundHistory.ts', import.meta.url), 'utf8');
const js = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022 } }).outputText;
const { readHistory, recordPlay, orderSounds, HISTORY_KEY } = await import('data:text/javascript;base64,' + Buffer.from(js).toString('base64'));
const stored = new Map();
globalThis.window = { localStorage: { getItem: key => stored.get(key) ?? null, setItem: (key, value) => stored.set(key, value) } };
const sounds = [{id:'subway'}, {id:'jazz'}, {id:'traffic'}, {id:'stream'}];
assert.deepEqual(orderSounds(sounds, readHistory()), sounds);
recordPlay('traffic'); recordPlay('jazz'); recordPlay('traffic');
assert.equal(readHistory().traffic.plays, 2);
assert.deepEqual(orderSounds(sounds, readHistory()).map(s => s.id), ['traffic','jazz','subway','stream']);
assert.deepEqual(sounds.map(s => s.id), ['subway','jazz','traffic','stream']);
assert.deepEqual(orderSounds(sounds,{jazz:{plays:2,lastPlayed:2},traffic:{plays:2,lastPlayed:3}}).map(s => s.id), ['traffic','jazz','subway','stream']);
stored.set(HISTORY_KEY, '{broken'); assert.deepEqual(readHistory(),{});
stored.set(HISTORY_KEY,JSON.stringify({jazz:{plays:-4,lastPlayed:1},traffic:{plays:'99',lastPlayed:1},stream:{plays:1,lastPlayed:8}}));
assert.deepEqual(orderSounds(sounds,readHistory()).map(s=>s.id),['stream','subway','jazz','traffic']);
window.localStorage.getItem=()=>{throw new Error('storage blocked');};
window.localStorage.setItem=()=>{throw new Error('storage blocked');};
assert.doesNotThrow(()=>recordPlay('jazz')); assert.deepEqual(readHistory(),{});
delete globalThis.window; assert.deepEqual(readHistory(),{});
console.log('PASS: persisted play counts, frequency ranking, recency ties, stable defaults, corrupt and blocked storage.');
